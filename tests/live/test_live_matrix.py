@pytest.fixture(scope="session")
def built(warehouse: Warehouse, live_config: Any) -> Any:
    """Build every shape once, in parallel, and drop them all afterwards.

    Yields {shape name: fully qualified table name, or the build error}. A shape
    the workspace cannot create (a preview that is off) is skipped, not failed.
    """
    run_id = uuid.uuid4().hex[:8]
    names = {s.name: f"{live_config.prefix}.dsm_{run_id}_{s.name}" for s in SHAPES}

    def build(shape: Shape) -> tuple[str, str | None]:
        full = names[shape.name]
        try:
            for statement in shape.statements:
                warehouse.run(statement.format(t=full))
        except Exception as exc:
            return shape.name, str(exc)[:300]
        return shape.name, None

    with concurrent.futures.ThreadPoolExecutor(8) as pool:
        errors = dict(pool.map(build, SHAPES))
    try:
        yield {n: (names[n] if errors[n] is None else RuntimeError(errors[n])) for n in names}
    finally:
        for shape in SHAPES:
            with contextlib.suppress(Exception):
                warehouse.run(f"DROP TABLE IF EXISTS {names[shape.name]}")
            for suffix in ("_rf", "_mask"):
                with contextlib.suppress(Exception):
                    warehouse.run(f"DROP FUNCTION IF EXISTS {names[shape.name]}{suffix}")


