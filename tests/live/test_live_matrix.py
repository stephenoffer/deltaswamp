writable = pytest.mark.parametrize(
    "shape", [s for s in SHAPES if s.writes], ids=[s.name for s in SHAPES if s.writes]
)


class TestWrites:
    """Managed tables grant no external writes, so these go through the warehouse."""

    @writable
    def test_append_delete_update_merge(
        self, shape: Shape, built: Any, fallback: Any, warehouse: Warehouse
    ) -> None:
        name = _table_for(built, shape)
        table = fallback.table(name)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            before = warehouse.count(name)
            batch = pa.table(table.head(2))
            table.append(batch)
            assert warehouse.count(name) == before + batch.num_rows

            target = warehouse.ids(name)[0]
            gone = warehouse.count(name, f"id = {target}")
            table.delete(f"id = {target}")
            assert warehouse.count(name) == before + batch.num_rows - gone

            table.update(updates={"id": "id + 1000000"}, predicate="id < 3")
            moved = warehouse.count(name, "id >= 1000000")
            assert warehouse.count(name) == before + batch.num_rows - gone

            source = pa.table(table.head(1))
            (
                table.merge(source, "target.id = source.id")
                .when_matched_update_all()
                .when_not_matched_insert_all()
                .execute()
            )
            assert warehouse.count(name) == before + batch.num_rows - gone
            assert warehouse.count(name, "id >= 1000000") == moved

    @writable
    def test_maintenance_and_ddl(
        self, shape: Shape, built: Any, fallback: Any, warehouse: Warehouse
    ) -> None:
        name = _table_for(built, shape)
        table = fallback.table(name)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            table.optimize()
            table.vacuum(dry_run=True)
            if "clustered" in shape.tags:
                assert not table.can(Operation.ZORDER).ok
            else:
                table.z_order(["id"])
            table.add_column({"dsm_extra": "STRING"})
            assert "dsm_extra" in warehouse.columns(name)
            table.set_properties({"deltaswamp.matrix": "yes"})
            props = {r[0]: r[1] for r in warehouse.rows(f"SHOW TBLPROPERTIES {name}")}
            assert props.get("deltaswamp.matrix") == "yes"
            table.unset_properties(["deltaswamp.matrix"])
            table.set_comment("matrix")
            if table.can(Operation.DROP_COLUMN).ok:
                table.drop_column("dsm_extra")

    @writable
    def test_restore(self, shape: Shape, built: Any, fallback: Any, warehouse: Warehouse) -> None:
        name = _table_for(built, shape)
        table = fallback.table(name)
        want = warehouse.count(name, suffix=" VERSION AS OF 1")
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            table.restore(1)
        assert warehouse.count(name) == want
        assert pa.table(fallback.table(name).to_arrow()).num_rows == want


