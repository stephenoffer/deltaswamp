# ------------------------------------------------------------------ plumbing


class Warehouse:
    """Ground truth: what Databricks itself says is in the table."""

    def __init__(self, workspace: Any, warehouse_id: str) -> None:
        self.workspace = workspace
        self.warehouse_id = warehouse_id

    def run(self, sql: str) -> Any:
        api = self.workspace.statement_execution
        r = api.execute_statement(warehouse_id=self.warehouse_id, statement=sql, wait_timeout="50s")
        while r.status.state.value in ("PENDING", "RUNNING"):
            time.sleep(1)
            r = api.get_statement(r.statement_id)
        if r.status.error:
            raise RuntimeError(f"{sql[:80]!r}: {r.status.error.message}")
        return r

    def rows(self, sql: str) -> list[list[Any]]:
        r = self.run(sql)
        return (r.result.data_array or []) if r.result else []

    def count(self, name: str, where: str | None = None, suffix: str = "") -> int:
        clause = f" WHERE {where}" if where else ""
        return int(self.rows(f"SELECT count(*) FROM {name}{suffix}{clause}")[0][0])

    def columns(self, name: str) -> list[str]:
        return [c.name for c in self.run(f"SELECT * FROM {name} LIMIT 0").manifest.schema.columns]

    def ids(self, name: str) -> list[int]:
        return sorted(int(r[0]) for r in self.rows(f"SELECT id FROM {name}") if r[0] is not None)


