def _table_for(built: dict[str, Any], shape: Shape) -> str:
    name = built[shape.name]
    if isinstance(name, Exception):
        pytest.skip(f"this workspace cannot build {shape.name}: {name}")
    return str(name)


def _ids(table: Any) -> list[int] | None:
    if "id" not in table.column_names:
        return None
    return sorted(x for x in table.column("id").to_pylist() if x is not None)


def _agrees(got: Any, warehouse: Warehouse, name: str) -> None:
    assert got.num_rows == warehouse.count(name)
    assert got.column_names == warehouse.columns(name)
    ids = _ids(got)
    if ids is not None:
        assert ids == warehouse.ids(name)


shapes = pytest.mark.parametrize("shape", SHAPES, ids=[s.name for s in SHAPES])


# --------------------------------------------------------------------- reads


class TestReads:
    @shapes
    def test_direct_read_agrees_or_refuses(
        self, shape: Shape, built: Any, direct: Any, warehouse: Warehouse
    ) -> None:
        """A direct engine either reads exactly what Databricks sees, or says why not."""
        name = _table_for(built, shape)
        table = direct.table(name)
        verdict = table.can(Operation.SCAN)
        if shape.direct_read is None:
            if verdict.ok:
                try:
                    got = pa.table(table.to_arrow())
                except Exception as exc:
                    assert str(exc), "a failed read must say why"
                    return
                _agrees(got, warehouse, name)
            return
        assert verdict.ok is shape.direct_read, verdict
        if verdict.ok:
            _agrees(pa.table(table.to_arrow()), warehouse, name)
        else:
            assert verdict.reason

    @shapes
    def test_fallback_read_agrees(
        self, shape: Shape, built: Any, fallback: Any, warehouse: Warehouse
    ) -> None:
        name = _table_for(built, shape)
        _agrees(pa.table(fallback.table(name).to_arrow()), warehouse, name)

    @shapes
    def test_predicate_agrees(
        self, shape: Shape, built: Any, fallback: Any, warehouse: Warehouse
    ) -> None:
        name = _table_for(built, shape)
        if shape.predicate is None:
            pytest.skip("no predicate for this shape")
        got = pa.table(fallback.table(name).to_arrow(predicate=shape.predicate)).num_rows
        assert got == warehouse.count(name, shape.predicate)

    @shapes
    def test_time_travel_to_the_first_version(
        self, shape: Shape, built: Any, fallback: Any, warehouse: Warehouse
    ) -> None:
        name = _table_for(built, shape)
        if not shape.time_travel:
            verdict = fallback.table(name).can(Operation.TIME_TRAVEL)
            assert not verdict.ok
            assert "row filter" in verdict.reason or "column mask" in verdict.reason
            return
        want = warehouse.count(name, suffix=" VERSION AS OF 0")
        assert pa.table(fallback.table(name).to_arrow(version=0)).num_rows == want

    @shapes
    def test_claimed_log_reads_work(self, shape: Shape, built: Any, fallback: Any) -> None:
        """If deltaswamp says it can, it must -- the claim is the contract."""
        name = _table_for(built, shape)
        table = fallback.table(name)
        for op, call in (
            (Operation.HISTORY, table.history),
            (Operation.DETAIL, table.detail),
            (Operation.FILES, table.files),
        ):
            verdict = table.can(op)
            if verdict.ok:
                call()
            else:
                assert verdict.reason, f"{op.value} refused silently"

    @shapes
    def test_features_match_describe_detail(
        self, shape: Shape, built: Any, fallback: Any, warehouse: Warehouse
    ) -> None:
        import json

        name = _table_for(built, shape)
        r = warehouse.run(f"DESCRIBE DETAIL {name}")
        detail = dict(
            zip([c.name for c in r.manifest.schema.columns], r.result.data_array[0], strict=True)
        )
        want = set(json.loads(detail["tableFeatures"] or "[]"))
        got = set(fallback.table(name).features())
        # A legacy protocol implies its features rather than listing them.
        if int(detail["minWriterVersion"]) < 7:
            assert got <= want
        else:
            assert got == want

    def test_change_data_feed_agrees(self, built: Any, fallback: Any, warehouse: Warehouse) -> None:
        name = _table_for(built, BY_NAME["change_data_feed"])
        table = fallback.table(name)
        assert table.can(Operation.CDF).engine is Engine.KERNEL
        got = pa.table(table.cdf(starting_version=0)).num_rows
        assert got == warehouse.count(f"table_changes('{name}', 0)")

    def test_collated_predicates_never_go_direct(self, built: Any, direct: Any) -> None:
        """Byte comparison gives a wrong answer here, not an error."""
        name = _table_for(built, BY_NAME["collation"])
        with pytest.raises(ds.DeltaSwampError, match="collat"):
            direct.table(name).to_arrow(predicate="name = 'oslo'")

    def test_masks_and_filters_are_applied(self, built: Any, fallback: Any) -> None:
        masked = pa.table(fallback.table(_table_for(built, BY_NAME["column_mask"])).to_arrow())
        assert set(masked.column("city").to_pylist()) == {"***"}
        filtered = pa.table(fallback.table(_table_for(built, BY_NAME["row_filter"])).to_arrow())
        assert "oslo" not in filtered.column("city").to_pylist()


