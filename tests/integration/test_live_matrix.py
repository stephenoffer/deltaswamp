@dataclass(frozen=True)
class Shape:
    """One table shape: how to build it, and what deltaswamp should make of it."""

    name: str
    statements: tuple[str, ...]
    #: Whether a direct engine (kernel or delta-rs) should serve a plain scan.
    #: None: it may be claimed -- nothing in the log decides it -- but a claimed
    #: read must then agree with the warehouse or fail loudly.
    direct_read: bool | None = True
    #: Whether earlier versions are readable at all. Databricks refuses time
    #: travel on a table with a row filter or column mask.
    time_travel: bool = True
    #: The predicate used to compare filtered reads against the warehouse.
    predicate: str | None = "id < 5"
    #: Exercised by the write tests.
    writes: bool = False
    tags: frozenset[str] = field(default_factory=frozenset)


def _shape(name: str, *statements: str, **kwargs: Any) -> Shape:
    return Shape(name, statements, **kwargs)


def _ins() -> str:
    return f"INSERT INTO {{t}} VALUES {_ROWS}"


