"""Every Delta table shape Databricks produces, read and written through deltaswamp.

The live suite in test_live_databricks.py exercises one scratch table. This
module builds one table per shape -- deletion vectors present, column mapping
after renames, liquid clustering, type widening, variant, collations, row
filters, clones, catalog-managed, and so on -- and checks every answer against
the warehouse, which is ground truth for what Databricks considers the table's
contents.

Two kinds of assertion, and the second matters more:

* reads agree with the warehouse, row for row;
* a claim is honest: when `can()` says yes the call succeeds, and when a
  direct engine cannot serve a shape the refusal names why.

Opt-in on top of the live suite, because it creates ~35 tables:

    DELTASWAMP_TEST_MATRIX=1 pytest tests/integration/test_live_matrix.py -v

It needs DELTASWAMP_TEST_WAREHOUSE_ID (the fixtures are built through it) and
creates a staging volume in the target schema for the write tests.
"""

