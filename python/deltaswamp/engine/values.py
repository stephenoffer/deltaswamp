"""Column values a kernel write computes and checks itself.

delta-kernel 0.28 refuses to write a table whose schema uses generated
columns, identity columns or column invariants. Spark computes and checks
these as it writes each row; the kernel write paths here do the same, over
every batch before it reaches the native writer, and then tell the commit
which features they stood in for (``values_checked=``, `crate::restate`):

* A **generated column** the data leaves out is computed from its generation
  expression; one the data gives is checked to equal it (null-safe), as
  Spark's ``g <=> expr`` constraint does. Values are stored as Spark stores
  an expression's result into the column's type.
* An **identity column** the data leaves out is filled from a block of values
  the table's high-water mark already covers (`IdentityBlock`): reserved by
  the commit itself for a local append, and by a metadata-only commit before
  the job for a distributed one, so workers need no coordination and the
  data commit changes no metadata. A value the data gives is refused for
  GENERATED ALWAYS, and kept for GENERATED BY DEFAULT without moving the
  high-water mark -- as Spark does; ``ALTER TABLE ... SYNC IDENTITY`` exists
  for exactly that.
* A **column invariant** is a CHECK over the row: evaluated with the table's
  CHECK constraints (`constraints.ConstraintCheck`).
* A left-out column with a literal **DEFAULT** gets it, as `Table.append`
  gives it.

Expressions are Spark SQL, respelled for DuckDB and evaluated in the sandboxed
in-memory DuckDB `engine.duckfilter` sets up. One DuckDB cannot evaluate as
Databricks does is refused when the write is planned, never partway through.
"""

